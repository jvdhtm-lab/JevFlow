from django.conf import settings
from django.db import models
from base.models import TenantBaseModel
from base.constants import (
    INTEGRATION_PURPOSE_CHOICES,
    INTEGRATION_TYPE_CHOICES,
    INTEGRATION_STATUS_CHOICES,
    OUTBOUND_AUTH_SCHEME_CHOICES,
    WEBHOOK_SOURCE_CHOICES,
    WEBHOOK_DIRECTION_CHOICES,
    INBOUND_WEBHOOK_PATH,
    SYNC_DIRECTION_CHOICES,
    SYNC_RESULT_CHOICES,
)


class Integration(TenantBaseModel):
    """A customer's external system connection (action/trigger world).

    User-identity providers (git / gmail / outlook / slack login) live in
    identity_api and are unrelated. ``purpose`` keeps the two worlds explicit.
    """
    purpose = models.CharField(
        max_length=20, choices=INTEGRATION_PURPOSE_CHOICES, default='action_trigger'
    )
    integration_type = models.CharField(max_length=30, choices=INTEGRATION_TYPE_CHOICES)
    base_url = models.URLField(max_length=500, null=True, blank=True)
    connection_status = models.CharField(
        max_length=20, choices=INTEGRATION_STATUS_CHOICES, default='pending'
    )
    config = models.JSONField(null=True, blank=True)
    credentials_hint = models.CharField(max_length=500, null=True, blank=True)
    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='owned_integrations'
    )
    last_sync_at = models.DateTimeField(null=True, blank=True)
    last_error = models.TextField(null=True, blank=True)


class WebhookEndpoint(TenantBaseModel):
    """A defined hook on an action/trigger integration (VHRS: TenantBaseModel).

    - inbound: ONE fixed URL shared by every inbound hook
      (``INBOUND_WEBHOOK_PATH``). The per-customer ``secret`` — generated by
      us, given to the customer — identifies whose call it is. Trigger nodes
      bind via ``config.webhook_endpoint``.
    - outbound: URL + auth are BOTH provided by the customer (``target_url``
      plus ``auth_scheme``/``auth_username``/``auth_token``). Action nodes
      bind via ``config.webhook_endpoint``.
    """
    integration = models.ForeignKey(
        Integration, on_delete=models.CASCADE, related_name='webhook_endpoints'
    )
    direction = models.CharField(
        max_length=10, choices=WEBHOOK_DIRECTION_CHOICES, default='inbound'
    )
    secret = models.CharField(max_length=200, null=True, blank=True, unique=True)
    source = models.CharField(max_length=20, choices=WEBHOOK_SOURCE_CHOICES, default='generic')
    target_path = models.CharField(max_length=500)
    # Customer-provided outbound destination (full URL) and credentials.
    target_url = models.URLField(max_length=500, null=True, blank=True)
    auth_scheme = models.CharField(
        max_length=10, choices=OUTBOUND_AUTH_SCHEME_CHOICES, default='none'
    )
    auth_username = models.CharField(max_length=200, null=True, blank=True)
    auth_token = models.TextField(null=True, blank=True)
    is_active = models.BooleanField(default=True)
    last_received_at = models.DateTimeField(null=True, blank=True)

    def save(self, *args, **kwargs):
        import secrets as _secrets

        if self.direction == 'inbound':
            # One fixed hook URL for everyone; the secret is the identity.
            self.target_path = INBOUND_WEBHOOK_PATH
            if not self.secret:
                self.secret = _secrets.token_urlsafe(32)
        super().save(*args, **kwargs)


class SyncLog(TenantBaseModel):
    integration = models.ForeignKey(
        Integration, on_delete=models.CASCADE, null=True, blank=True,
        related_name='sync_logs',
    )
    direction = models.CharField(max_length=10, choices=SYNC_DIRECTION_CHOICES, default='in')
    event_type = models.CharField(max_length=100)
    payload = models.JSONField(null=True, blank=True)
    result = models.CharField(max_length=20, choices=SYNC_RESULT_CHOICES, default='success')
    error_msg = models.TextField(null=True, blank=True)
    duration_ms = models.IntegerField(null=True, blank=True)
